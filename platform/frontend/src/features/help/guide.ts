export function searchHelp(query:string,sectionId='all'):HelpSection[]{
  const needle=normalizeSearch(query)
  return helpSections.filter(section=>sectionId==='all'||section.id===sectionId).map(section=>({
    ...section,items:section.items.filter(item=>!needle||normalizeSearch(`${section.title} ${item.question} ${item.answer}`).includes(needle)),
  })).filter(section=>section.items.length>0)
}
